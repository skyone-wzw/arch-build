"""Configuration (packages.toml) and lockfile (packages.lock) models."""

from __future__ import annotations

import os
import re
import tomllib
from pathlib import Path

import tomlkit
from pydantic import BaseModel, ConfigDict, Field, ValidationError, field_validator

from arch_build import CONFIG_FILE, LOCK_FILE

_SAFE_IDENT_RE = re.compile(r"^[A-Za-z0-9._+-]+$")


class AurConfig(BaseModel):
    model_config = ConfigDict(strict=True)

    packages: list[str] = Field(default_factory=list)

    @field_validator("packages")
    @classmethod
    def _validate_unique(cls, values: list[str]) -> list[str]:
        seen: set[str] = set()
        duplicates: set[str] = set()
        for name in values:
            if name in seen:
                duplicates.add(name)
            seen.add(name)
        if duplicates:
            raise ValueError(f"duplicate AUR packages: {sorted(duplicates)}")
        return values


class RepoConfig(BaseModel):
    model_config = ConfigDict(strict=True)

    name: str | None = None
    tag: str = "pacman"

    @field_validator("name")
    @classmethod
    def _validate_name(cls, value: str | None) -> str | None:
        if value is not None and not _SAFE_IDENT_RE.fullmatch(value):
            raise ValueError(f"invalid repository name: {value!r}")
        return value

    @field_validator("tag")
    @classmethod
    def _validate_tag(cls, value: str) -> str:
        if not _SAFE_IDENT_RE.fullmatch(value):
            raise ValueError(f"invalid release tag: {value!r}")
        return value


class BuildConfig(BaseModel):
    model_config = ConfigDict(strict=True)

    skip_pgpcheck: bool = False


class Config(BaseModel):
    model_config = ConfigDict(strict=True)

    aur: AurConfig = Field(default_factory=AurConfig)
    repo: RepoConfig = Field(default_factory=RepoConfig)
    build: BuildConfig = Field(default_factory=BuildConfig)

    def resolved_repo_name(self) -> str:
        """Return the pacman database/section name, defaulting to the GitHub repo name."""
        if self.repo.name:
            return self.repo.name
        slug = os.environ.get("GITHUB_REPOSITORY", "")
        name = slug.rsplit("/", 1)[-1] if slug else "arch-build"
        if not _SAFE_IDENT_RE.fullmatch(name):
            raise ValueError(f"invalid repository name: {name!r}")
        return name


class LockEntry(BaseModel):
    model_config = ConfigDict(strict=True)

    name: str
    source: str = "aur"
    version: str = ""
    commit: str = ""
    pkgbase: str | None = None

    @property
    def effective_pkgbase(self) -> str:
        return self.pkgbase or self.name


class _LockDocument(BaseModel):
    model_config = ConfigDict(strict=True)

    version: int = 1
    package: list[LockEntry] = Field(default_factory=list)


def load_config(path: Path = CONFIG_FILE) -> Config:
    if not path.is_file():
        raise ValueError(f"missing configuration file: {path}")
    raw = tomllib.loads(path.read_text(encoding="utf-8"))
    try:
        return Config.model_validate(raw)
    except ValidationError as exc:
        raise ValueError(f"{path.name}: {exc}") from exc


def read_lock(path: Path = LOCK_FILE) -> dict[str, LockEntry]:
    if not path.is_file():
        return {}
    raw = tomllib.loads(path.read_text(encoding="utf-8"))
    try:
        doc = _LockDocument.model_validate(raw)
    except ValidationError as exc:
        raise ValueError(f"{path.name}: {exc}") from exc
    return {entry.name: entry for entry in doc.package}


def render_lock(entries: dict[str, LockEntry]) -> str:
    doc = tomlkit.document()
    doc.add(tomlkit.comment("Generated by arch-check-update -- do not edit manually."))
    doc.add(tomlkit.comment("Pins external (AUR) packages so that builds are reproducible."))
    doc.add(tomlkit.nl())
    doc.add("version", 1)

    if entries:
        packages = tomlkit.aot()
        for name in sorted(entries):
            entry = entries[name]
            table = tomlkit.table()
            table.add("name", entry.name)
            if entry.pkgbase and entry.pkgbase != entry.name:
                table.add("pkgbase", entry.pkgbase)
            table.add("source", entry.source)
            table.add("version", entry.version)
            table.add("commit", entry.commit)
            packages.append(table)
        doc.add("package", packages)

    return tomlkit.dumps(doc).rstrip("\n") + "\n"
